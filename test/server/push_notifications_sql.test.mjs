import { pathToFileURL } from 'node:url';
const { PGlite } = await import(process.env.PGLITE_MODULE ? pathToFileURL(process.env.PGLITE_MODULE).href : '@electric-sql/pglite');
const migration = readFileSync(new URL('../../supabase/migrations/20260908094551_targeted_push_notifications.sql', import.meta.url), 'utf8');
const enqueueMigration = readFileSync(new URL('../../supabase/migrations/20261019114718_push_enqueue_preferences_and_quiet_hours.sql', import.meta.url), 'utf8');
const alice = '11111111-1111-1111-1111-111111111111', bob = '22222222-2222-2222-2222-222222222222';
const tokenA = 'test-alice-installation-token', tokenB = 'test-bob-installation-token';
test('real notification migration enforces recipients, immutable contents, event delivery and leases', async () => {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      create function auth.role() returns text language sql stable as $$ select current_setting('request.jwt.claim.role',true) $$;
      grant usage on schema auth,public to authenticated,service_role;
      create table public.profiles(id uuid primary key references auth.users(id));
      create table public.albums(id bigint primary key, owner_id uuid, title text);
      create table public.album_members(album_id bigint,user_id uuid,role text default 'EDITOR',status text default 'ACCEPTED');
      create table public.orders(order_id text primary key,user_id uuid,status text);
      create table public.templates(id bigint primary key,title text,is_active boolean);
      create table public.notifications(id bigint generated by default as identity primary key,
        user_id uuid references auth.users(id),type text,title text,body text,deeplink text,
        is_read boolean default false,created_at timestamptz default now(),read_at timestamptz);
      alter table public.notifications enable row level security;
      create table public.notification_inbox(id bigint);
      create table public.notification_reads(id bigint);
      grant all on public.notification_inbox,public.notification_reads to authenticated;
      insert into auth.users values ('${alice}'),('${bob}');
      insert into profiles values ('${alice}'),('${bob}');
      insert into albums values (1,'${alice}','Private album');
    `);
    await db.exec(migration);
    await db.exec(enqueueMigration);
    const login = async (user) => db.exec(`reset role; set role authenticated;
      select set_config('request.jwt.claim.sub','${user}',false);
      select set_config('request.jwt.claim.role','authenticated',false);`);
    const server = async () => db.exec(`reset role; set role service_role;
      select set_config('request.jwt.claim.role','service_role',false);`);
    await server();
    assert.equal((await db.query('select cleanup_notifications() as n')).rows[0].n, 0);
    assert.equal((await db.query('select * from claim_push_deliveries(25)')).rows.length, 0);
    await login(alice);
    await db.query('select register_push_device($1,\'android\',540,true)', [tokenA]);
    // This recipient/security scenario must not depend on the wall-clock hour.
    await db.exec(`insert into push_preferences(user_id,night_mute) values ('${alice}',false)`);
    await assert.rejects(db.query('select claim_push_deliveries(25)'), /permission denied/);
    await assert.rejects(db.query('select * from notification_inbox'), /permission denied/);
    await assert.rejects(db.exec(`insert into push_preferences(user_id) values ('${bob}')`), /row-level security/);
    await login(bob);
    await db.query('select register_push_device($1,\'iOS\',540,true)', [tokenB]);
    assert.equal((await db.query('select * from push_devices')).rows.length, 1);
    await db.exec('reset role;');
    await db.exec(`insert into orders values ('ord_a','${alice}','PAYMENT_PENDING');`);
    assert.equal((await db.query('select count(*)::int as n from notifications')).rows[0].n, 0);
    await db.exec(`update orders set status='SHIPPING' where order_id='ord_a';`);
    await db.exec(`update orders set status='SHIPPING' where order_id='ord_a';`);
    assert.equal((await db.query('select count(*)::int as n from notifications')).rows[0].n, 1);
    const queue = (await db.query('select * from push_outbox')).rows;
    assert.equal(queue.length, 1); assert.equal(queue[0].token, tokenA); assert.equal(queue[0].user_id, alice);
    await login(bob);
    assert.equal((await db.query('select * from notifications')).rows.length, 0);
    await login(alice);
    await assert.rejects(db.exec(`update notifications set title='forged'`), /permission denied/);
    await assert.rejects(db.exec(`update notifications set user_id='${bob}'`), /permission denied/);
    await db.exec('update notifications set is_read=true,read_at=now() where is_read=false;');
    await db.exec('update notifications set is_read=true,read_at=now() where is_read=false;');
    assert.equal((await db.query('select is_read from notifications')).rows[0].is_read, true);
    await server();
    const firstClaim = (await db.query('select * from claim_push_deliveries(25)')).rows;
    assert.equal(firstClaim.length, 1); assert.ok(firstClaim[0].lease_token);
    assert.equal((await db.query('select * from claim_push_deliveries(25)')).rows.length, 0);
    await db.exec(`update push_outbox set locked_until=now()-interval '1 second'`);
    const nextClaim = (await db.query('select * from claim_push_deliveries(25)')).rows[0];
    assert.equal(nextClaim.attempts, 2); assert.notEqual(nextClaim.lease_token, firstClaim[0].lease_token);
    await login(bob);
    await db.query('select register_push_device($1,\'android\',0,true)', [tokenA]);
    await server();
    assert.equal((await db.query(`select o.id from push_outbox o join push_devices d on d.token=o.token and d.user_id=o.user_id`)).rows.length, 0);
    await db.exec('reset role;');
    await db.exec(`insert into album_members values (1,'${bob}','EDITOR','ACCEPTED');`);
    const invite = (await db.query(`select * from notifications where type='invite_accepted'`)).rows[0];
    assert.equal(invite.user_id, alice); assert.equal(invite.data.albumId, 1);
    assert.ok(!('inviteToken' in invite.data));
    await db.exec(`update album_members set status='ACCEPTED' where album_id=1;`);
    assert.equal((await db.query(`select count(*)::int as n from notifications where type='invite_accepted'`)).rows[0].n, 1);
    await db.exec(`insert into templates values (9,'New template',true); update templates set is_active=true where id=9;`);
    assert.equal((await db.query(`select count(*)::int as n from notifications where type='template_new'`)).rows[0].n, 2);
    await db.exec(`update notifications set created_at=now()-interval '91 days' where type='order_status';`);
    await login(alice);
    assert.equal((await db.query(`select * from notifications where type='order_status'`)).rows.length, 0);
    await server();
    await db.query('select cleanup_notifications()');
    assert.equal((await db.query(`select * from notifications where type='order_status'`)).rows.length, 0);
  } finally { await db.close(); }
});

async function enqueueDatabase() {
  const db = new PGlite();
  try {
    await db.exec(`
      create role anon; create role authenticated; create role service_role bypassrls;
      create schema auth; create table auth.users(id uuid primary key);
      create function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;
      create function auth.role() returns text language sql stable as $$ select 'service_role'::text $$;
      create table public.profiles(id uuid primary key);
      create table public.albums(id bigint primary key,owner_id uuid,title text);
      create table public.album_members(album_id bigint,user_id uuid,role text,status text);
      create table public.orders(order_id text,user_id uuid,status text);
      create table public.templates(id bigint primary key,title text,is_active boolean);
      create table public.notifications(id bigint generated by default as identity primary key,
        user_id uuid,type text,title text,body text,deeplink text,is_read boolean default false,
        created_at timestamptz default now(),read_at timestamptz);
      alter table public.notifications enable row level security;
      create table public.notification_inbox(id bigint); create table public.notification_reads(id bigint);
      insert into auth.users values ('${alice}'),('${bob}');
    `);
    await db.exec(migration);
    await db.exec(enqueueMigration);
    await db.exec(`
      insert into public.push_devices(token,user_id,platform,timezone_offset_minutes,enabled) values
        ('${tokenA}','${alice}','android',540,true),
        ('test-alice-western-timezone','${alice}','iOS',-240,true),
        ('test-alice-disabled-device','${alice}','android',540,false),
        ('test-alice-stale-device-token','${alice}','android',540,true),
        ('${tokenB}','${bob}','iOS',540,true);
      update public.push_devices set updated_at=now()-interval '91 days' where token='test-alice-stale-device-token';
      -- Explicit UTC conversion in the trigger must ignore the SQL session zone.
      set time zone 'Pacific/Honolulu';
    `);
    return db;
  } catch (error) { await db.close(); throw error; }
}

async function enqueueEvent(db, { user = alice, category = 'order', createdAt = '2026-10-19T03:00:00Z' } = {}) {
  const inserted = (await db.query(`insert into public.notifications(user_id,type,category,title,body,created_at)
    values ($1,'fixture',$2,'offline event','offline event',$3) returning id`, [user, category, createdAt])).rows[0];
  return (await db.query('select token from public.push_outbox where notification_id=$1 order by token', [inserted.id]))
    .rows.map(row => row.token);
}

test('enqueue uses every event-time preference without losing inbox rows or reviving opt-out events', async () => {
  const db = await enqueueDatabase();
  try {
    const allowed = [tokenA, 'test-alice-western-timezone'].sort();
    assert.deepEqual(await enqueueEvent(db), allowed);
    assert.deepEqual(await enqueueEvent(db, { category: 'marketing' }), []);
    assert.deepEqual(await enqueueEvent(db, { user: bob, category: 'new_template' }), [tokenB]);
    assert.deepEqual(await enqueueEvent(db, { user: bob, category: 'marketing' }), []);
    await db.exec(`insert into public.push_preferences(user_id) values ('${alice}')`);
    for (const [column, category] of [
      ['all_enabled', 'order'], ['order_enabled', 'order'], ['invite_enabled', 'invite'],
      ['comment_enabled', 'comment'], ['new_template_enabled', 'new_template'],
      ['marketing_enabled', 'marketing'],
    ]) {
      await db.exec(`update public.push_preferences set ${column}=false where user_id='${alice}'`);
      const before = (await db.query('select count(*)::int as n from public.push_outbox')).rows[0].n;
      const inboxBefore = (await db.query('select count(*)::int as n from public.notifications')).rows[0].n;
      assert.deepEqual(await enqueueEvent(db, { category }), [], column);
      assert.equal((await db.query('select count(*)::int as n from public.notifications')).rows[0].n, inboxBefore + 1);
      await db.exec(`update public.push_preferences set ${column}=true where user_id='${alice}'`);
      assert.equal((await db.query('select count(*)::int as n from public.push_outbox')).rows[0].n, before,
        'turning a preference back on must not enqueue old suppressed events');
      assert.deepEqual(await enqueueEvent(db, { category }), allowed, column);
    }
    await db.exec(`update public.push_preferences set all_enabled=false where user_id='${alice}'`);
    for (const category of ['order', 'invite', 'comment', 'marketing', 'new_template', 'general']) {
      assert.deepEqual(await enqueueEvent(db, { category }), [], category);
    }
    assert.deepEqual(await enqueueEvent(db, { user: bob }), [tokenB], 'another account stays unaffected');
  } finally { await db.close(); }
});

test('enqueue applies per-device quiet boundaries and keeps quiet events out after 08:00', async () => {
  const db = await enqueueDatabase();
  try {
    await db.exec(`insert into public.push_preferences(user_id,night_mute) values ('${alice}',true)`);
    const western = 'test-alice-western-timezone';
    const both = [tokenA, western].sort();
    for (const [createdAt, expected] of [
      ['2026-10-19T12:59:59Z', both], // KST 21:59:59; UTC-4 08:59:59.
      ['2026-10-19T13:00:00Z', [western]], // KST 22:00 is quiet.
      ['2026-10-19T22:59:59Z', [western]], // KST 07:59:59 is still quiet.
      ['2026-10-19T23:00:00Z', both], // KST 08:00 is allowed.
      ['2026-10-19T03:00:00Z', [tokenA]], // KST noon; UTC-4 previous-day 23:00.
    ]) {
      assert.deepEqual(await enqueueEvent(db, { createdAt }), expected, createdAt);
    }
    const before = (await db.query('select count(*)::int as n from public.push_outbox')).rows[0].n;
    await db.exec(`update public.push_preferences set night_mute=false where user_id='${alice}'`);
    assert.equal((await db.query('select count(*)::int as n from public.push_outbox')).rows[0].n, before);
    assert.deepEqual(await enqueueEvent(db, { createdAt: '2026-10-19T13:00:00Z' }), both);
  } finally { await db.close(); }
});
