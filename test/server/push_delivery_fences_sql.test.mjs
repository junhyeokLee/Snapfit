test('final policy returns an absolute quiet boundary from the latest device and preference row',async()=>{const db=await fixture();try{
 await comment(db,1);const row=await claim(db);
 // The initial worker snapshot may have night_mute=false. Change it before
 // prepare, and place this device at 21:58 without depending on wall-clock hour.
 await db.exec(`update public.push_devices set timezone_offset_minutes=
  mod(21*60+58-(extract(hour from(clock_timestamp()at time zone'UTC'))::int*60+
  extract(minute from(clock_timestamp()at time zone'UTC'))::int)+2160,1440)-720;
  insert into public.push_preferences(user_id,night_mute)values('${alice}',true);`);
 const decision=await prepared(db,row);assert.equal(decision.allowed,true);
 assert.equal(typeof decision.expiresAt,'string');
 const remaining=await scalar(db,"select extract(epoch from($1::timestamptz-clock_timestamp()))::float8 r",[decision.expiresAt]);
 assert.ok(remaining>0&&remaining<=120,`latest quiet-hour TTL must be at most 120s, got ${remaining}`);
 const hour=await scalar(db,"select extract(hour from(($1::timestamptz at time zone'UTC')+timezone_offset_minutes*interval'1 minute'))::int r from public.push_devices",[decision.expiresAt]);
 assert.equal(hour,22);
 await db.exec('update public.push_preferences set night_mute=false');
 const unrestricted=await prepared(db,row);
 const full=await scalar(db,"select extract(epoch from($1::timestamptz-clock_timestamp()))::float8 r",[unrestricted.expiresAt]);
 assert.ok(full>299&&full<=300);
}finally{await db.close();}});
