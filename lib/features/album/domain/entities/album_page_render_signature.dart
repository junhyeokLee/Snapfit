import 'album_page.dart';

int albumPageRenderSignature(AlbumPage page) => Object.hashAll([
  page.id,
  page.backgroundColor,
  ...page.layers.map(
    (layer) => Object.hashAll([
      layer.id,
      layer.type,
      layer.asset?.id,
      layer.previewUrl,
      layer.originalUrl,
      layer.imageUrl,
      layer.position,
      layer.width,
      layer.height,
      layer.scale,
      layer.rotation,
      layer.opacity,
      layer.zIndex,
      layer.imageBackground,
      layer.imageTemplate,
      layer.imageOffset,
      layer.imageZoom,
      layer.text,
      layer.textStyle,
      layer.textStyleType,
      layer.textAlign,
      layer.textBackground,
      layer.textFillMode,
      layer.textFillImageUrl,
      layer.bubbleColor,
      layer.decorationFillColor,
      layer.decorationBorderColor,
      layer.decorationBorderWidth,
      layer.decorationCornerRadius,
    ]),
  ),
]);
