/// Lightweight authored metadata. No document or decoded image is retained here.
class StoryEdition {
  const StoryEdition({
    required this.id,
    required this.catalogId,
    required this.title,
    required this.category,
    required this.englishTitle,
    required this.subtitle,
    required this.coverStyle,
    required this.photoAssets,
    required this.chapters,
    required this.paperLabel,
    required this.motifLabel,
    required this.ink,
    required this.tint,
    required this.accent,
    this.exclusivePhotography = false,
    this.notes = const [],
    this.discoveryTags = const [],
    this.isPremium = true,
    this.qualityRevision,
    this.activity,
    this.memberSlots = 0,
    this.photoFrames = const [],
    this.photoAspectRatios = const [],
    this.preservedPhotoFrames = const [],
    this.additionalMaterialKeys = const [],
    this.innerPages = 24,
    this.spreadOrder = const [],
  });
  final String id,
      title,
      category,
      englishTitle,
      subtitle,
      paperLabel,
      motifLabel;
  final int catalogId, coverStyle;
  final List<String> photoAssets, chapters;
  final String ink, tint, accent;
  final bool exclusivePhotography;
  final bool isPremium;
  final String? qualityRevision;
  final StoryActivity? activity;
  final int memberSlots;
  final List<String> notes;
  final List<String> discoveryTags;

  List<String> get styleTags =>
      (qualityRevision == premiumQuartetRevision
          ? premiumQuartetCoverStyleTags[coverStyle]
          : storyCoverStyleTags[coverStyle]) ??
      const [];

  /// Existing frame products curated for the book, separate from its own kit.
  final List<String> photoFrames;

  /// Read from asset headers at authoring time; never opens images at runtime.
  final List<double> photoAspectRatios;
  final List<String> preservedPhotoFrames;
  final List<String> additionalMaterialKeys;
  final int innerPages;
  final List<int> spreadOrder;
  static const innerPageCount = 24;
  String get productKey => 'template:$id';
  String get paperId => '$id-paper';
  String get motifId => '$id-motif';
  String get wordArtId => id;
  String get phraseKey => 'phrase:collage-$wordArtId';
  String get coverAsset => photoAssets.first;
  List<String> get materialKeys => [
    'sticker:$paperId',
    'sticker:$motifId',
    phraseKey,
  ];
  List<String> get includedMaterialKeys => [
    ...materialKeys,
    ...additionalMaterialKeys,
    for (final frame in {...photoFrames, ...preservedPhotoFrames})
      'frame:$frame',
  ];
}

