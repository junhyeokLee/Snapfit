void _studioMilestoneCover(_StudioPage p, StudioEdition e) {
  p.photo('cover_photo', e.coverAsset, 0, 0, 1, 1);
  _coverShade(p, top: false, strength: .23);
  final wedding = e.weddingEdition;
  final ink = wedding ? (e.premium ? '#4C2939' : '#193C4E') : '#173B50';
  p.type(
    wedding
        ? (e.premium ? 'A VOW TO KEEP' : 'OUR FIRST PROMISE')
        : (e.premium
              ? 'LITTLE EXPLORER / VOL. 01'
              : 'LITTLE DAYS, BIG DISCOVERIES'),
    .065,
    .035,
    .87,
    .04,
    size: .017,
    font: 'Poppins',
    weight: 600,
    color: ink,
  );
  if (e == StudioEdition.littleExplorerBook) {
    p.type(
      '꼬마\n탐험사전',
      .06,
      .085,
      .35,
      .18,
      size: .062,
      font: 'NotoSans',
      weight: 800,
      color: ink,
    );
  } else if (e == StudioEdition.velvetVowArchive) {
    p.type(
      '벨벳 서약집',
      .065,
      .105,
      .87,
      .14,
      size: .084,
      font: 'BookMyungjo',
      weight: 800,
      color: ink,
    );
  } else {
    final title = wedding
        ? (p.wide ? '우리의\n첫 약속' : '우리의 첫 약속')
        : (p.wide ? '작은 날의\n발견' : '작은 날의 발견');
    p.type(
      title,
      .065,
      .105,
      p.wide ? .31 : .87,
      p.wide ? .25 : .12,
      size: wedding ? .071 : .065,
      font: wedding ? 'BookMyungjo' : 'NotoSans',
      weight: 600,
      color: ink,
    );
  }
  p.type(
    wedding ? '함께한 시작, 오래 펼쳐 볼 약속' : '작은 발견으로 자라는 너의 하루',
    .07,
    .91,
    .86,
    .045,
    size: .022,
    font: 'Eulyoo',
    color: '#FFFFFF',
  );
}

void _milestoneLabel(
  _StudioPage p,
  String text,
  double x,
  double y,
  double w,
) => p.type(text, x, y, w, .04, size: .017, font: 'Poppins', weight: 600);

void _milestoneTitle(
  _StudioPage p,
  String text,
  double x,
  double y,
  double w,
  double h, {
  double size = .066,
  String? color,
}) {
  p.type(
    text,
    x,
    y,
    w,
    h,
    size: size,
    color: color,
    font: p.edition.weddingEdition ? 'BookMyungjo' : 'NotoSans',
    weight: p.edition.premium ? 800 : 600,
  );
  p.layers.last['typographyRole'] = 'milestone-title';
}

void _milestoneCaption(
  _StudioPage p,
  String text,
  double x,
  double y,
  double w,
  double h,
) {
  p.type(
    text,
    x,
    y,
    w,
    h,
    size: .030,
    font: p.edition.weddingEdition ? 'Eulyoo' : 'NotoSans',
  );
  p.layers.last['typographyRole'] = 'milestone-caption';
}

/// Match text to the material's real aspect, not to its requested bounding box.
void _milestoneNote(
  _StudioPage p,
  String key,
  String text,
  double x,
  double y,
  double w,
  double h,
) {
  final ratio = studioDecorationById(key)!.aspectRatio;
  final width = math.min(w, h * ratio / p.ratio),
      height = width * p.ratio / ratio;
  p.mat(key, x, y, w, h);
  final materialId = p.layers.last['id'];
  _fittedEditorialType(
    p,
    p.uid,
    text,
    Rect.fromLTWH(x + width * .13, y + height * .19, width * .72, height * .58),
    size: .027,
    color: '#333B40',
    font: 'Eulyoo',
    leading: 1.3,
    maxLines: text.split('\n').length,
  );
  p.layers.last['materialContentOf'] = materialId;
  p.layers.last['typographyRole'] = 'milestone-note';
}
