import 'dart:convert';
import 'dart:io';

/// Uses the active SDK and the target's package language version for both
/// generation and --check. No temporary source or preview files are written.
Future<void> generateAiContract({
  required List<String> args,
  required String sourcePath,
  required String targetPath,
  required String constantName,
  required String generatorPath,
}) async {
  if (args.any((arg) => arg != '--check')) {
    stderr.writeln('Usage: dart run $generatorPath [--check]');
    exitCode = 64;
    return;
  }
  final data = jsonDecode(File(sourcePath).readAsStringSync());
  final body =
      '// Generated by $generatorPath. Do not edit.\n'
      'const $constantName = '
      '${const JsonEncoder.withIndent('  ').convert(data)};\n';
  final formatter = await Process.start(Platform.resolvedExecutable, [
    'format',
    '--output=show',
    '--show=none',
    '--summary=none',
    '--stdin-name=$targetPath',
  ]);
  final output = formatter.stdout.transform(utf8.decoder).join();
  final errors = formatter.stderr.transform(utf8.decoder).join();
  formatter.stdin.encoding = utf8;
  formatter.stdin.write(body);
  await formatter.stdin.close();
  final status = await formatter.exitCode;
  final formatted = await output;
  final errorText = await errors;
  if (status != 0 || formatted.isEmpty) {
    throw StateError('Could not format $targetPath: $errorText');
  }
  final target = File(targetPath);
  if (args.contains('--check')) {
    if (!target.existsSync() || target.readAsStringSync() != formatted) {
      stderr.writeln('$targetPath is stale. Run dart run $generatorPath');
      exitCode = 1;
    }
    return;
  }
  target.writeAsStringSync(formatted);
}
