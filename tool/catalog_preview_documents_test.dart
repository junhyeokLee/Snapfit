import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:snap_fit/core/data/catalog_preview_document.dart';
import 'package:snap_fit/core/data/catalog_preview_documents.g.dart';
import 'package:snap_fit/core/templates/template_document_pages.dart';
import 'package:snap_fit/features/album/data/bundled_creation_templates.dart';

// Generate exact layouts using the app's real fonts on Flutter's root isolate:
// flutter test --dart-define=UPDATE_CATALOG_PREVIEWS=true tool/catalog_preview_documents_test.dart
// Check freshness without changing files:
// flutter test tool/catalog_preview_documents_test.dart
void main() {
  TestWidgetsFlutterBinding.ensureInitialized();

  test('published preview snapshots match current artwork and bundled fonts', () async {
    final manifestSource = await rootBundle.loadString('FontManifest.json');
    final manifest = jsonDecode(manifestSource) as List;
    final fontHashes = <String>[manifestSource];
    for (final font in manifest) {
      final loader = FontLoader(font['family'] as String);
      for (final asset in font['fonts'] as List) {
        final path = asset['asset'] as String;
        final bytes = await rootBundle.load(path);
        fontHashes.add(
          '$path:${sha256.convert(bytes.buffer.asUint8List(bytes.offsetInBytes, bytes.lengthInBytes))}',
        );
        loader.addFont(Future.value(bytes));
      }
      await loader.load();
    }
    final digest = sha256
        .convert(utf8.encode(fontHashes.join('\n')))
        .toString();
    final actual = <int, String>{};
    // Initialize the registry only after every native font has loaded. Export
    // and check run in fresh Flutter processes so lazy builder caches agree.
    for (final template in publishedCreationTemplates) {
      final source = template.templateJson!;
      final compact = compactCatalogPreviewDocument(source)!;
      final pages = templateDocumentPages(
        jsonDecode(source) as Map<String, dynamic>,
      );
      expect(compact['cover'], pages.first['layers'], reason: template.title);
      expect(compact['spread'], [
        pages[3]['layers'],
        pages[4]['layers'],
      ], reason: template.title);
      expect(
        compact.keys,
        unorderedEquals(['width', 'height', 'cover', 'spread', 'profile']),
      );
      actual[template.id] = jsonEncode(compact);
    }

    if (const bool.fromEnvironment('UPDATE_CATALOG_PREVIEWS')) {
      String literal(String value) => jsonEncode(value).replaceAll(r'$', r'\$');
      File('lib/core/data/catalog_preview_documents.g.dart').writeAsStringSync(
        '// Generated by tool/catalog_preview_documents_test.dart. Do not edit.\n'
        '// Native font layout; only cover, pages 3/4, and profile cross to the UI.\n'
        '// Regenerate: flutter test --dart-define=UPDATE_CATALOG_PREVIEWS=true tool/catalog_preview_documents_test.dart\n'
        'const catalogPreviewFontDigest =\n    ${literal(digest)};\n'
        'const catalogPreviewDocuments = <int, String>{\n'
        '${actual.entries.map((entry) => '  ${entry.key}:\n      ${literal(entry.value)},').join('\n')}\n'
        '};\n',
      );
    } else {
      expect(
        catalogPreviewFontDigest,
        digest,
        reason: 'Bundled fonts changed; regenerate catalog preview documents.',
      );
      expect(catalogPreviewDocuments.keys, unorderedEquals(actual.keys));
      for (final entry in actual.entries) {
        expect(
          jsonDecode(catalogPreviewDocuments[entry.key]!),
          jsonDecode(entry.value),
          reason:
              'Stale live artwork for ${entry.key}. Regenerate catalog preview documents.',
        );
      }
    }
  }, timeout: const Timeout(Duration(minutes: 3)));
}
