-- AI album draft point ledger and first-free usage tracking.
--
-- Policy intent:
-- - direct/manual album creation never touches points.
-- - AI album draft consumes points only after a reviewable draft succeeds.
-- - each user gets one successful AI draft free credit.
-- - failure states are not recorded here and must not mutate point balances.
-- - Flutter clients cannot directly change balances; they call the security-definer RPC.

create table if not exists public.point_wallets (
  user_id uuid primary key references auth.users(id) on delete cascade,
  balance integer not null default 0 check (balance >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

drop trigger if exists point_wallets_set_updated_at on public.point_wallets;
create trigger point_wallets_set_updated_at
before update on public.point_wallets
for each row execute function public.set_updated_at();

create table if not exists public.point_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  amount_delta integer not null,
  reason text not null check (
    reason in (
      'AI_ALBUM_DRAFT_FREE',
      'AI_ALBUM_DRAFT_CHARGE',
      'ADMIN_ADJUSTMENT',
      'POINT_PURCHASE'
    )
  ),
  idempotency_key text not null unique,
  related_entity_type text,
  related_entity_id text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists point_ledger_user_created_idx
on public.point_ledger(user_id, created_at desc);

create table if not exists public.ai_album_draft_usages (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  draft_id text not null,
  point_cost integer not null default 300 check (point_cost >= 0),
  used_free_credit boolean not null default false,
  status text not null default 'SUCCEEDED' check (status in ('SUCCEEDED','VOIDED')),
  created_at timestamptz not null default now(),
  unique (user_id, draft_id)
);

create index if not exists ai_album_draft_usages_user_created_idx
on public.ai_album_draft_usages(user_id, created_at desc);

create table if not exists public.ai_album_free_draft_claims (
  user_id uuid primary key references auth.users(id) on delete cascade,
  draft_id text not null,
  claimed_at timestamptz not null default now()
);

alter table public.point_wallets enable row level security;
alter table public.point_ledger enable row level security;
alter table public.ai_album_draft_usages enable row level security;
alter table public.ai_album_free_draft_claims enable row level security;

