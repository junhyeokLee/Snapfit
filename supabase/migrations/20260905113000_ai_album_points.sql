create or replace function public.record_ai_album_draft_success(
  p_draft_id text,
  p_point_cost integer default 300
)
returns table (
  used_free_credit boolean,
  charged_points integer,
  remaining_balance integer
)
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_existing public.ai_album_draft_usages%rowtype;
  v_wallet_balance integer;
  v_used_free boolean := false;
begin
  if v_user_id is null then
    raise exception 'record_ai_album_draft_success requires an authenticated user'
      using errcode = '28000';
  end if;

  if p_draft_id is null or btrim(p_draft_id) = '' then
    raise exception 'draft id is required'
      using errcode = '22023';
  end if;

  if p_point_cost is null or p_point_cost < 0 then
    raise exception 'point cost must be zero or positive'
      using errcode = '22023';
  end if;

  select *
  into v_existing
  from public.ai_album_draft_usages
  where user_id = v_user_id
    and draft_id = p_draft_id;

  if found then
    select coalesce(balance, 0)
    into v_wallet_balance
    from public.point_wallets
    where user_id = v_user_id;

    return query select
      v_existing.used_free_credit,
      case when v_existing.used_free_credit then 0 else v_existing.point_cost end,
      coalesce(v_wallet_balance, 0);
    return;
  end if;

  insert into public.point_wallets(user_id, balance)
  values (v_user_id, 0)
  on conflict (user_id) do nothing;

  v_used_free := not exists (
    select 1
    from public.ai_album_free_draft_claims
    where user_id = v_user_id
  );

  if v_used_free then
    insert into public.ai_album_free_draft_claims(user_id, draft_id)
    values (v_user_id, p_draft_id);

    insert into public.ai_album_draft_usages(
      user_id,
      draft_id,
      point_cost,
      used_free_credit
    ) values (
      v_user_id,
      p_draft_id,
      0,
      true
    );

    insert into public.point_ledger(
      user_id,
      amount_delta,
      reason,
      idempotency_key,
      related_entity_type,
      related_entity_id,
      metadata
    ) values (
      v_user_id,
      0,
      'AI_ALBUM_DRAFT_FREE',
      'ai_album_draft_free:' || v_user_id::text || ':' || p_draft_id,
      'ai_album_draft',
      p_draft_id,
      jsonb_build_object('point_cost', 0)
    );

    select balance
    into v_wallet_balance
    from public.point_wallets
    where user_id = v_user_id;

    return query select true, 0, v_wallet_balance;
    return;
  end if;

  select balance
  into v_wallet_balance
  from public.point_wallets
  where user_id = v_user_id
  for update;

  if v_wallet_balance < p_point_cost then
    raise exception 'insufficient points for AI album draft'
      using errcode = 'P0001';
  end if;

  update public.point_wallets
  set balance = balance - p_point_cost
  where user_id = v_user_id
  returning balance into v_wallet_balance;

  insert into public.ai_album_draft_usages(
    user_id,
    draft_id,
    point_cost,
    used_free_credit
  ) values (
    v_user_id,
    p_draft_id,
    p_point_cost,
    false
  );

  insert into public.point_ledger(
    user_id,
    amount_delta,
    reason,
    idempotency_key,
    related_entity_type,
    related_entity_id,
    metadata
  ) values (
    v_user_id,
    -p_point_cost,
    'AI_ALBUM_DRAFT_CHARGE',
    'ai_album_draft_charge:' || v_user_id::text || ':' || p_draft_id,
    'ai_album_draft',
    p_draft_id,
    jsonb_build_object('point_cost', p_point_cost)
  );

  return query select false, p_point_cost, v_wallet_balance;
end;
$$;

revoke all on function public.record_ai_album_draft_success(text, integer) from public;
grant execute on function public.record_ai_album_draft_success(text, integer) to authenticated;
